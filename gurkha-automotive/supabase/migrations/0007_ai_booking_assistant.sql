-- ---------------------------------------------------------------
-- 3. Booking references
-- ---------------------------------------------------------------
-- "GA-" + 6 characters from an alphabet without look-alikes (no 0/O,
-- 1/I/L), so a reference read out over the phone is unambiguous.
-- References are not secrets — nothing can be looked up by reference
-- without signing in as an admin — so random() is sufficient; the
-- unique index is the real guarantee.
create or replace function public.generate_booking_reference()
returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  candidate text;
  i integer;
begin
  loop
    candidate := 'GA-';
    for i in 1..6 loop
      candidate := candidate || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1);
    end loop;
    exit when not exists (select 1 from public.bookings where reference = candidate);
  end loop;
  return candidate;
end;
$$;

update public.bookings
set reference = public.generate_booking_reference()
where reference is null;

alter table public.bookings alter column reference set default public.generate_booking_reference();
alter table public.bookings alter column reference set not null;
create unique index if not exists bookings_reference_key on public.bookings (reference);

-- ---------------------------------------------------------------
-- 4. No overlapping active bookings — enforced by Postgres itself.
-- ---------------------------------------------------------------
-- An exclusion constraint is checked atomically, including against
-- other transactions that are still in flight, so two simultaneous
-- requests for the same slot cannot both succeed: the second gets
-- SQLSTATE 23P01, which the API turns into "that slot was just taken".
--
-- "Active" matches the existing scheduling rule (anything not
-- cancelled holds its slot), with the new "rejected" status also
-- releasing it. Listed positively so this file never references the
-- 'rejected' enum value added by 0006.
--
-- tsrange on built-in types needs no extension (no btree_gist).
alter table public.bookings drop constraint if exists bookings_no_overlap;
alter table public.bookings add constraint bookings_no_overlap
  exclude using gist (
    tsrange(booking_date + start_time, booking_date + end_time, '[)') with &&
  )
  where (status in ('pending', 'confirmed', 'completed'));

-- ---------------------------------------------------------------
-- 5. Admin authorisation
-- ---------------------------------------------------------------
-- Until now every authenticated user was treated as an admin. If
-- public sign-ups are enabled in Supabase Auth (the default), anyone
-- could create an account with the public anon key and read every
-- customer's booking. Admin access now requires a row here.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  note text check (note is null or char_length(note) <= 200),
  created_at timestamptz not null default now()
);

comment on table public.admin_users is
  'Supabase Auth users allowed into the admin dashboard. Manage from the SQL editor; there is deliberately no API to add admins.';

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users where user_id = auth.uid()
  );
$$;

comment on function public.is_admin() is
  'True when the calling Supabase Auth user is listed in public.admin_users.';

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated, service_role;


create table if not exists public.booking_events (
  id bigint generated always as identity primary key,
  booking_id uuid not null references public.bookings (id) on delete cascade,
  event_type text not null check (
    event_type in ('created', 'status_changed', 'rescheduled', 'notes_updated', 'email_sent', 'email_failed')
  ),
  from_status text,
  to_status text,
  from_date date,
  from_start_time time,
  to_date date,
  to_start_time time,
  detail text check (detail is null or char_length(detail) <= 500),
  actor_id uuid,
  actor_email text,
  created_at timestamptz not null default now()
);

comment on table public.booking_events is
  'Append-only history of each booking: creation, status changes, reschedules, note edits and email outcomes.';

create index if not exists booking_events_booking_idx
  on public.booking_events (booking_id, created_at);

alter table public.booking_events enable row level security;

drop policy if exists "Admins can view booking events" on public.booking_events;
create policy "Admins can view booking events"
  on public.booking_events for select to authenticated

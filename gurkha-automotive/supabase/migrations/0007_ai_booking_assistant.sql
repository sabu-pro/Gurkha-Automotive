-- Gurkha Automotive — Booking assistant, references, history,
-- double-booking protection and admin authorisation
-- =============================================================
-- PREREQUISITE: 0006_booking_status_rejected.sql must already have
-- been run (and committed) — run it on its own first.
--
-- Nothing in this file deletes data. In order, it:
--   1. Aborts early, with a clear message, if existing bookings
--      already overlap (the new constraint in step 4 would fail).
--   2. Adds new columns to public.bookings (all nullable or with
--      defaults, so existing rows and the existing form keep working).
--   3. Gives every existing booking a reference like GA-7K3QX9.
--   4. Adds a database-level constraint so two active bookings can
--      never overlap — even if two customers submit at the same
--      instant. Previously this was only checked in application code
--      between a SELECT and an INSERT, which leaves a race window.
--   5. Introduces public.admin_users + public.is_admin(), and switches
--      every admin RLS policy from "any signed-in user" to "a user
--      listed in admin_users". EVERY EXISTING AUTH USER IS COPIED INTO
--      admin_users, so nobody who can sign in today loses access.
--      Review that list afterwards (see the query at the bottom).
--   6. Adds public.booking_events, an audit trail written by a trigger.
--
-- Re-runnable: every statement is guarded (if not exists / drop if
-- exists), so running it twice is harmless.

-- ---------------------------------------------------------------
-- 1. Pre-flight: refuse to continue if active bookings overlap.
-- ---------------------------------------------------------------
do $$
declare
  overlap_count integer;
begin
  select count(*) into overlap_count
  from public.bookings a
  join public.bookings b
    on a.id < b.id
   and a.booking_date = b.booking_date
   and a.start_time < b.end_time
   and b.start_time < a.end_time
  where a.status in ('pending', 'confirmed', 'completed')
    and b.status in ('pending', 'confirmed', 'completed');

  if overlap_count > 0 then
    raise exception
      'Found % pair(s) of overlapping active bookings. Resolve them (cancel or move one of each pair) and re-run this migration. List them with the query in the comment at the bottom of this file.',
      overlap_count;
  end if;
end
$$;


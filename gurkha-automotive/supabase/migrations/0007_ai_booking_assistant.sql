-- No write policies: rows come from the trigger below (security
-- definer) or from server code using the service role.

create or replace function public.log_booking_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_email text := nullif(auth.jwt() ->> 'email', '');
begin
  if tg_op = 'INSERT' then
    insert into public.booking_events
      (booking_id, event_type, to_status, to_date, to_start_time, detail, actor_id, actor_email)
    values
      (new.id, 'created', new.status::text, new.booking_date, new.start_time,
       'Submitted via ' || new.source, v_actor, v_email);
    return new;
  end if;

  if new.status is distinct from old.status then
    insert into public.booking_events
      (booking_id, event_type, from_status, to_status, detail, actor_id, actor_email)
    values
      (new.id, 'status_changed', old.status::text, new.status::text,
       case when new.status_reason is distinct from old.status_reason then new.status_reason end,
       v_actor, v_email);
  end if;

  if new.booking_date is distinct from old.booking_date
     or new.start_time is distinct from old.start_time then
    insert into public.booking_events
      (booking_id, event_type, from_date, from_start_time, to_date, to_start_time, detail, actor_id, actor_email)
    values
      (new.id, 'rescheduled', old.booking_date, old.start_time, new.booking_date, new.start_time,
       case when new.status_reason is distinct from old.status_reason then new.status_reason end,
       v_actor, v_email);
  end if;

  if new.admin_notes is distinct from old.admin_notes then
    insert into public.booking_events (booking_id, event_type, actor_id, actor_email)
    values (new.id, 'notes_updated', v_actor, v_email);
  end if;

  return new;
end;
$$;

drop trigger if exists bookings_log_event on public.bookings;
create trigger bookings_log_event
  after insert or update on public.bookings
  for each row
  execute function public.log_booking_event();

